import assert from "node:assert/strict";
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { after, test } from "node:test";
import { fileURLToPath } from "node:url";
import { git, gitOk } from "../src/git.ts";
import { aiAttribution } from "../src/git/attribution.ts";
import { configure, tempDir, cleanDirs } from "./git-helper.ts";

after(cleanDirs);

test("refused messages: any AI attribution", () => {
  for (const message of [
    "ajout\n\nCo-Authored-By: Claude Opus 5.5 <noreply@anthropic.com>",
    "ajout\n\nco-authored-by: claude <x@y.z>",
    "ajout\n\nCo-authored-by: GitHub Copilot <copilot@github.com>",
    "ajout\n\nSigned-off-by: ChatGPT <bot@openai.com>",
    "ajout\n\nCo-Authored-By: quelqu'un <noreply@anthropic.com>",
    "ajout\n\n🤖 Generated with [Claude Code](https://claude.com/claude-code)",
    "ajout\n\nGenerated by Codex",
    "ajout\n\nAssisted-by: IA",
  ]) {
    assert.ok(aiAttribution(message), `devrait être refusé : ${JSON.stringify(message)}`);
  }
});

test("allowed messages: mentioning AI is not claiming it", () => {
  for (const message of [
    "docs: verifications Claude Code du perimetre du kit",
    "hook commit-msg : refus de toute attribution IA",
    "ajout\n\nCo-Authored-By: Alice Martin <alice@exemple.fr>",
    "ajout\n\n# Co-Authored-By: Claude (ligne de commentaire de git)",
    "maj de l'adaptateur Godot\n\nStory-Head: 0123456789abcdef0123456789abcdef01234567",
  ]) {
    assert.equal(aiAttribution(message), null, `devrait être permis : ${JSON.stringify(message)}`);
  }
});

test("hook installed through core.hooksPath: git commit refused then accepted", () => {
  const repo = tempDir("commit-msg");
  gitOk(repo, ["init", "--quiet", "-b", "main"]);
  configure(repo);
  gitOk(repo, ["config", "core.hooksPath", fileURLToPath(new URL("../git-hooks/", import.meta.url))]);
  writeFileSync(join(repo, "a.txt"), "a\n");
  gitOk(repo, ["add", "a.txt"]);

  const refusal = git(repo, ["commit", "--quiet", "-m", "ajout", "-m", "Co-Authored-By: Claude <noreply@anthropic.com>"]);
  assert.notEqual(refusal.code, 0, "le commit attribué doit échouer");
  assert.match(refusal.stderr, /commit refusé/);
  assert.equal(git(repo, ["rev-parse", "--verify", "--quiet", "HEAD"]).code, 1, "aucun commit créé");

  gitOk(repo, ["commit", "--quiet", "-m", "ajout du fichier a"]);
  assert.equal(gitOk(repo, ["log", "--format=%s"]), "ajout du fichier a");
});
